const ICON_MAP: Record<string, (props: { className?: string }) => React.ReactElement> = {
  Instagram: IconInstagram,
  TikTok:    IconTikTok,
  YouTube:   IconYouTube,
  LinkedIn:  IconLinkedIn,
};

type Props = {
  variant?: "light" | "navy";
  className?: string;
};

export default function SocialLinks({ variant = "light", className }: Props) {
  const colorClass =
    variant === "navy"
      ? "text-on-navy-muted hover:text-on-navy"
      : "text-muted hover:text-accent";

  return (
    <div
      className={["flex items-center gap-4", className].filter(Boolean).join(" ")}
      aria-label="Social media links"
    >
      {creator.socials.map(({ platform, url }) => {
        const Icon = ICON_MAP[platform];
        if (!Icon) return null;
        return (
          <a
            key={platform}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={platform}
            className={["transition-colors duration-150", colorClass].join(" ")}
          >
            <Icon className="w-5 h-5" />
          </a>
        );
      })}
    </div>
  );
}
